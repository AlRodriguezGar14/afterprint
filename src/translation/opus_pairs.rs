#[cfg(test)]
mod tests {
    use super::model;

    #[test]
    fn examples_resolve_as_documented() {
        let direct = model("de", "en").unwrap();
        assert_eq!(direct.suffix, "de-en");
        assert_eq!(direct.input_prefix, None);

        let grouped_target = model("en", "pt").unwrap();
        assert_eq!(grouped_target.suffix, "en-ROMANCE");
        assert_eq!(grouped_target.input_prefix.as_deref(), Some(">>pt<<"));

        let grouped_source = model("ro", "en").unwrap();
        assert_eq!(grouped_source.suffix, "ROMANCE-en");
        assert_eq!(grouped_source.input_prefix, None);

        assert!(model("en", "km").is_none());
    }
}
