// Resolves CLI language codes to the variable parts of a managed OPUS model:
//
//   model("de", "en") -> suffix "de-en",       input_prefix None
//   model("en", "pt") -> suffix "en-ROMANCE", input_prefix Some(">>pt<<")
//   model("ro", "en") -> suffix "ROMANCE-en", input_prefix None
//   model("en", "km") -> None
//
// `suffix` completes `Helsinki-NLP/opus-mt-{suffix}`. `input_prefix`, when
// present, is prepended to every source unit to select the grouped model's
// target language.
//
// When the model has multiple output targets, >><< syntax is required: https://huggingface.co/Helsinki-NLP/opus-mt-en-ROMANCE/blob/main/README.md
//
// Exact direct-model pairs were found in the official Helsinki-NLP Hugging
// Face catalog on 2026-08-06 and restricted to afterprint's accepted language
// codes. Keep this allowlist local: managed downloads must never be built from
// unchecked user input.
pub(super) struct Model {
    pub suffix: String,
    pub input_prefix: Option<String>,
}

pub(super) fn model(source: &str, target: &str) -> Option<Model> {
    if DIRECT.contains(&(source, target)) {
        return Some(Model {
            suffix: format!("{source}-{target}"),
            input_prefix: None,
        });
    }

    GROUPED.iter().find_map(|group| {
        if !group.sources.contains(&source) {
            return None;
        }
        let (_, token) = group
            .targets
            .iter()
            .find(|&&(language, _)| language == target)?;

        Some(Model {
            suffix: group.suffix.into(),
            input_prefix: group.target_prefix.then(|| format!(">>{token}<<")),
        })
    })
}

